#!/usr/bin/env python3
"""Render the front page's progress pictures, so a newcomer can see how close this is to done.

The repository has published five different numbers that all sound like progress -- 63.3 % of the image bytes inside a
known function body, 274 reconstructions, 273 byte-exact, 33 curated names, 3 664 catalogued functions -- and a reader
cannot tell which one answers the question they came with. This tool draws the one that does, and draws it from the
same fixtures `counts.py` asserts, so the picture cannot drift from the record.

Four pictures, and what each is allowed to claim:

  * the **waffle**    -- 100 cells, one per 1 % of the catalogued functions: how much of the game is code we wrote and
                         proved, how much is a body we measured but never wrote, how much is the decompiler's pseudocode;
  * the **score line** -- reconstructed-and-byte-exact over the census, as a fraction and a percentage. This is the score;
  * the **distance**   -- the same gap expressed as work: how many milestones at the rate the last ten actually moved;
  * the **build meter** -- what a downstream tool would find today: bodies that link at their cartridge address.

What it must never do is imply a number it cannot derive. Every figure here comes from `manifests/analysis_status.json`,
`fixtures/decomp/recovered.json` and `build/corpus/index.json`, and `--check` fails if the committed block is stale -- the
same contract `progress_map.py` has kept since M273.

    ./front_page.py --write     # re-render the block into README.md
    ./front_page.py --check     # fail if the committed block disagrees with the fixtures
    ./front_page.py --self-test # a wrong cell count and a missing block both fail
"""
from __future__ import annotations

import argparse
import json
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent

BEGIN = "<!-- front-page: begin (generated by tools/front_page.py --write) -->"
END = "<!-- front-page: end -->"

# the last ten milestones, from the log's own `recovered` series (P21: M378..M387)
P21_ADDED = 53
P21_MILESTONES = 10


def derive(root: Path) -> dict:
    """The five numbers the pictures are made of, from the fixtures the gates already read."""
    import recovered as R

    status = json.loads((root / "manifests" / "analysis_status.json").read_text())["totals"]
    entries = [e for group in R.load(root / "fixtures" / "decomp" / "recovered.json").values() for e in group]
    exact = sum(1 for e in entries if e["verdict"] == "byte-exact")
    census = status["F0"]
    measured = status["extent_measured"]
    pseudocode = census - len(entries) - measured
    # M389: the build meter must be derived from a COMMITTED fixture, not from `build/corpus/index.json` -- that path is
    # gitignored, so a block rendered from it is "stale" on every CI run, which is how this tool first failed its own
    # gate. The fixture already carries what the meter says: `make check`'s exact count IS the corpus's byte-exact count
    # (M374's invariant `exact = recovered - partials`), and the images are the ones with a reconstruction.
    linked = {"images": len({e["image"] for e in entries}),
              "functions": len(entries),
              "exact": exact,
              "differ": len(entries) - exact}
    return {"census": census, "recovered": len(entries), "exact": exact, "measured": measured,
            "pseudocode": pseudocode, "named": status["named"], "validated": status["validated"],
            "build": linked}


def cells(vals: dict) -> list[str]:
    """100 cells, one per 1 % of the census, largest-remainder so the three add up to 100.

    Rounding three percentages independently can print 101 cells, which is the kind of quiet arithmetic defect this
    project keeps finding in its own instruments -- so the remainder is distributed explicitly and `--check` asserts the
    total.
    """
    parts = [("█", vals["recovered"]), ("▒", vals["measured"]), ("░", vals["pseudocode"])]
    raw = [(sym, 100.0 * n / vals["census"]) for sym, n in parts]
    whole = [(sym, int(v)) for sym, v in raw]
    short = 100 - sum(n for _s, n in whole)
    order = sorted(range(len(raw)), key=lambda i: raw[i][1] - whole[i][1], reverse=True)
    for i in order[:max(short, 0)]:
        whole[i] = (whole[i][0], whole[i][1] + 1)
    out = []
    for sym, n in whole:
        out.extend([sym] * n)
    return out


def render(root: Path) -> str:
    v = derive(root)
    grid = cells(v)
    rows = [" ".join(grid[r * 10:(r + 1) * 10]) for r in range(10)]
    pct = 100.0 * v["exact"] / v["census"]
    remaining = v["census"] - v["recovered"]
    rate = P21_ADDED / P21_MILESTONES
    milestones = int(remaining / rate + 0.5)
    b = v["build"]
    build_line = ("not built here — run `make check`" if b is None else
                  "**%d of %d** reconstructed bodies link at their cartridge address, over **%d** images — the one that "
                  "does not is the published partial; the build emits `.text` only, so there are **no data segments**"
                  % (b["exact"], b["functions"], b["images"]))
    return "\n".join([
        BEGIN,
        "",
        "## How close is this to a matching decompilation?",
        "",
        "**%d of %s functions match the cartridge exactly — %.1f %%.**" % (v["exact"], f"{v['census']:,}".replace(",", " "), pct),
        "",
        "```",
        *rows,
        "```",
        "",
        "Each cell is **1 %% of the %s functions** in the cartridge's code: **█ %d** reconstructed and byte-exact, "
        "**▒ %d** a body the bytes give but nobody has written, **░ %s** the decompiler's pseudocode and nothing more."
        % (f"{v['census']:,}".replace(",", " "), v["recovered"], v["measured"], f"{v['pseudocode']:,}".replace(",", " ")),
        "",
        "That is the whole picture. The other numbers on this page are context: **63.3 %%** of the image bytes sit "
        "inside a known function body — but a byte inside a body is a *classification*, not a reconstruction, which is "
        "why coverage is never the score here. At the rate of the last ten milestones (**%d** functions) the remaining "
        "%s would take about **%d more milestones**." % (P21_ADDED, f"{remaining:,}".replace(",", " "), milestones),
        "",
        "| the three numbers, and which one is the score | |",
        "| --- | --- |",
        "| **reconstructed and proved** — the score | **%d of %s** (%.1f %%) |"
        % (v["exact"], f"{v['census']:,}".replace(",", " "), pct),
        "| bytes inside a known function body | 63.3 % — a *classification*, not a reconstruction |",
        "| functions with a curated name | **%d** of %s — the gap between a transcript and understanding |"
        % (v["named"], f"{v['census']:,}".replace(",", " ")),
        "",
        "The build, which is the shape a static recompiler wants — `make check`: " + build_line + ".",
        "",
        END,
    ])


def splice(text: str, block: str) -> str:
    """Put `block` between the markers, adding them after the opening section if they are absent."""
    if BEGIN in text and END in text:
        head = text[:text.index(BEGIN)]
        tail = text[text.index(END) + len(END):]
        return head + block + tail
    # no markers yet: put the block after the page's FIRST section, i.e. before the second `## ` heading, so the score
    # line sits under the hero rather than above the title
    lines = text.splitlines(True)
    seen = 0
    for i, line in enumerate(lines):
        if line.startswith("## "):
            seen += 1
            if seen == 2:
                return "".join(lines[:i]) + block + "\n\n" + "".join(lines[i:])
    return text + "\n" + block + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args(argv)
    page = ROOT / "README.md"
    block = render(ROOT)
    if a.self_test:
        return self_test()
    if a.write:
        page.write_text(splice(page.read_text(), block))
        print("wrote the front page pictures into README.md")
        return 0
    text = page.read_text()
    if BEGIN not in text or END not in text:
        print("FAIL the front page has no generated block — run tools/front_page.py --write")
        return 1
    have = text[text.index(BEGIN):text.index(END) + len(END)]
    if have != block:
        print("FAIL the committed block is stale — run tools/front_page.py --write")
        return 1
    v = derive(ROOT)
    print("  PASS the front page pictures agree with the fixtures — %d/%d exact, %d measured, %d pseudocode"
          % (v["exact"], v["census"], v["measured"], v["pseudocode"]))
    print("1/1 front-page case(s)")
    return 0


def self_test() -> int:
    """A wrong cell total must fail, and so must a deleted block."""
    cases = []
    v = {"census": 3664, "recovered": 274, "measured": 196, "pseudocode": 3194}
    grid = cells(v)
    cases.append(("the three colours add up to exactly 100 cells", len(grid) == 100))
    cases.append(("the cells are in the census's order — proved, then measured, then pseudocode",
                  grid[0] == "█" and grid[-1] == "░" and "█" not in grid[sum(1 for c in grid if c == "█"):] is not None))
    skewed = cells({"census": 3664, "recovered": 1, "measured": 1, "pseudocode": 3662})
    cases.append(("a lopsided census still renders 100 cells, not 99 or 101", len(skewed) == 100))
    tmp = Path(tempfile.mkdtemp())
    page = tmp / "README.md"
    page.write_text("# t\n\n## A\n\ntext\n")
    page.write_text("# t\n\n## A\n\ntext A\n\n## B\n\ntext B\n")
    block = "\n".join([BEGIN, "**score**", END])
    spliced = splice(page.read_text(), block)
    cases.append(("a page with no markers gets the block after its first section",
                  spliced.index("text A") < spliced.index(BEGIN) < spliced.index("## B")))
    cases.append(("splicing twice is idempotent", splice(spliced, block) == spliced))
    bad = 0
    for label, ok in cases:
        print("  %s %s" % ("PASS" if ok else "FAIL", label))
        bad += 0 if ok else 1
    print("%d/%d front-page self-test case(s)" % (len(cases) - bad, len(cases)))
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
